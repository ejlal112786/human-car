#!/usr/bin/env python3
"""Convert assets-src/quaternius-ultimate-gun-pack/Pistol_4.obj (CC0) into src/game/crime/pistolModel.ts.

Game frame: metres, +Z = barrel direction, +Y = up, +X = -OBJ z (keeps the handedness), origin at
the top of the grip (where the web of the hand sits). Parts:
  slide  = the slide body, front sight and rear sight posts (moves back when firing)
  frame  = everything else (frame, grip, trigger, trigger guard, hammer, barrel tip)
Each part is split per material (Black / Metal / LightMetal); triangles are fan-triangulated.
"""
import collections
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets-src', 'quaternius-ultimate-gun-pack', 'Pistol_4.obj')
OUT = os.path.join(ROOT, 'src', 'game', 'crime', 'pistolModel.ts')

SCALE = 0.095  # OBJ length 1.98 units -> 0.188 m (a typical compact pistol)
ORIGIN = (0.10, 0.55, 0.0)  # top of the grip in OBJ units

V, faces, cur = [], [], None
for line in open(SRC):
    p = line.split()
    if not p:
        continue
    if p[0] == 'v':
        V.append(tuple(map(float, p[1:4])))
    elif p[0] == 'usemtl':
        cur = p[1]
    elif p[0] == 'f':
        faces.append((cur, [int(x.split('/')[0]) - 1 for x in p[1:]]))

# Connected components (shared vertices).
par = list(range(len(V)))


def find(a):
    while par[a] != a:
        par[a] = par[par[a]]
        a = par[a]
    return a


for _, f in faces:
    for i in f[1:]:
        par[find(i)] = find(f[0])
comp_verts = collections.defaultdict(set)
for _, f in faces:
    comp_verts[find(f[0])].update(f)


def bounds(vs):
    xs = [V[i][0] for i in vs]
    ys = [V[i][1] for i in vs]
    return min(xs), max(xs), min(ys), max(ys)


def is_slide(c):
    x0, x1, y0, y1 = bounds(comp_verts[c])
    body = y0 > 0.65 and x0 < 0 and x1 > 1.5  # slide body
    front_sight = y0 > 1.04 and x0 > 1.3  # front sight blade
    rear_sight = y0 > 1.04 and -0.1 < x0 < 0.05  # rear sight posts
    return body or front_sight or rear_sight


def tr(i):
    x, y, z = V[i]
    return (
        round(-(z - ORIGIN[2]) * SCALE, 5),
        round((y - ORIGIN[1]) * SCALE, 5),
        round((x - ORIGIN[0]) * SCALE, 5),
    )


parts = {'slide': collections.defaultdict(list), 'frame': collections.defaultdict(list)}
for mat, f in faces:
    part = 'slide' if is_slide(find(f[0])) else 'frame'
    for k in range(1, len(f) - 1):
        # OBJ is counter-clockwise; the axis permutation with the z flip keeps the winding.
        parts[part][mat].extend([tr(f[0]), tr(f[k]), tr(f[k + 1])])

slide_vs = set().union(*[comp_verts[c] for c in comp_verts if is_slide(c)])
sx0, sx1, sy0, sy1 = bounds(slide_vs)
# Sight line: tops of the rear sight posts / front sight. Muzzle: front of the barrel tip.
rear = [i for i in slide_vs if V[i][1] > 1.04 and -0.1 < V[i][0] < 0.05]
front = [i for i in slide_vs if V[i][1] > 1.04 and V[i][0] > 1.3]
muzzle_vs = [i for i in range(len(V)) if V[i][0] > 1.58]
sight_y = (max(V[i][1] for i in rear) - ORIGIN[1]) * SCALE
rear_z = (sum(V[i][0] for i in rear) / len(rear) - ORIGIN[0]) * SCALE
front_z = (sum(V[i][0] for i in front) / len(front) - ORIGIN[0]) * SCALE
muzzle_y = (sum(V[i][1] for i in muzzle_vs) / len(muzzle_vs) - ORIGIN[1]) * SCALE
muzzle_z = (max(V[i][0] for i in muzzle_vs) - ORIGIN[0]) * SCALE
eject_z = ((sx0 + sx1) / 2 - 0.2 - ORIGIN[0]) * SCALE
eject_y = ((sy0 + sy1) / 2 - ORIGIN[1]) * SCALE


def arr(tris):
    return '[' + ','.join(f'{c:g}' for t in tris for c in t) + ']'


with open(OUT, 'w') as o:
    o.write('// Generated by scripts/gen-pistol.py from "Ultimate Gun Pack" Pistol_4 by Quaternius (CC0 1.0).\n')
    o.write('// Do not edit by hand. Metres; +Z = barrel, +Y = up; origin at the top of the grip.\n\n')
    o.write("export type PistolMaterial = 'Black' | 'Metal' | 'LightMetal';\n")
    o.write('/** Non-indexed triangle positions (x, y, z per vertex) per material. */\n')
    o.write('export type PistolPart = Partial<Record<PistolMaterial, readonly number[]>>;\n\n')
    for name in ('frame', 'slide'):
        o.write(f'export const PISTOL_{name.upper()}: PistolPart = {{\n')
        for mat, tris in sorted(parts[name].items()):
            o.write(f'  {mat}: {arr(tris)},\n')
        o.write('};\n\n')
    o.write('/** Reference points (model space, metres). */\n')
    o.write('export const PISTOL_POINTS = {\n')
    o.write(f'  /** Height of the sight line (tops of the sights) above the origin. */\n  sightY: {sight_y:.4f},\n')
    o.write(f'  rearSightZ: {rear_z:.4f},\n  frontSightZ: {front_z:.4f},\n')
    o.write(f'  muzzleY: {muzzle_y:.4f},\n  muzzleZ: {muzzle_z:.4f},\n')
    o.write(f'  /** Ejection port (right side of the slide). */\n  ejectX: {-0.16 * SCALE:.4f},\n  ejectY: {eject_y:.4f},\n  ejectZ: {eject_z:.4f},\n')
    o.write('} as const;\n')

print('wrote', OUT, {k: {m: len(t) // 3 for m, t in v.items()} for k, v in parts.items()})
print('sightY %.4f rearZ %.4f frontZ %.4f muzzle y %.4f z %.4f' % (sight_y, rear_z, front_z, muzzle_y, muzzle_z))

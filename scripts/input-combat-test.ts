/** Keyboard fallback controls for jail/free-roam combat, without a browser. */
declare const process: { exit(code: number): never };
import { InputManager, createControlState } from '../src/game/InputManager';

const listeners = new Map<string, (e: unknown) => void>();
const fakeTarget = { addEventListener: (name: string, cb: (e: unknown) => void) => listeners.set(name, cb) };
const canvasListeners = new Map<string, (e: unknown) => void>();
const fakeCanvas = { addEventListener: (name: string, cb: (e: unknown) => void) => canvasListeners.set(name, cb) };
Object.assign(globalThis, { window: fakeTarget, document: { addEventListener: () => undefined } });
let failures = 0;
const actions: string[] = [];
const check = (name: string, ok: boolean): void => { console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}`); if (!ok) failures++; };
const input = new InputManager((a) => actions.push(a));
input.capturing = true;
input.mouseWeapon = true;
const key = (name: string, code: string, repeat = false): void => listeners.get(name)?.({ code, repeat, isTrusted: false, preventDefault: () => undefined });
const out = createControlState();
key('keydown', 'KeyQ');
key('keydown', 'KeyZ');
input.read(out);
check('Q toggles aim and Z fires through the merged keyboard ControlState', out.aim && out.fire);
key('keyup', 'KeyZ');
input.read(out);
check('release Z stops firing while Q keeps aim toggled', out.aim && !out.fire);
key('keydown', 'Digit1');
check('1 dispatches the gun draw/holster action', actions.includes('weapon'));
input.clear();
input.read(out);
check('blur/clear releases fire and clears toggled aim', !out.aim && !out.fire);
input.mouseWeapon = false;
input.attachMouse(fakeCanvas as unknown as HTMLElement);
input.capturing = true;
canvasListeners.get('pointerdown')?.({ pointerType: 'mouse', buttons: 3, target: fakeCanvas });
input.mouseWeapon = true;
input.read(out);
check('left/right mouse chord produces aim and fire together', out.aim && out.fire);
listeners.get('pointerup')?.({ pointerType: 'mouse', buttons: 0, target: fakeCanvas });
input.read(out);
check('mouse release stops both trigger and aim', !out.aim && !out.fire);
input.mouseWeapon = false;
input.contribute(out);
check('mouse combat is gated when weapon is unavailable', !out.aim && !out.fire);
input.dispose();
if (failures) process.exit(1);
console.log('ALL COMBAT INPUT CHECKS PASSED');
